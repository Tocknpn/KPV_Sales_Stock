"""Build the Morning Market reset SQL from the case workbook (decided 2026-11-27).

    python -I scripts/build_mm_seed.py "ລາຍລະອຽດເຄື່ອງຕູ້_1-7 morning market actual.xlsx"

Writes two files and prints the list of spelling fixes applied:
  supabase/reset/20261127_morning_market_reset.sql   full wipe + load
  supabase/reset/20261127_mm_min_and_zero_opening.sql  fix for a database the
      first reset already loaded: openings to 0, minimums from column E
One sheet = one case (ຕູ້1..ຕູ້7 -> MM-D01..MM-D07).

Columns: A type, B grams per piece (merged down a group), C name, D detail,
E ຂັ້ນຕ່ຳທີ່ຕ້ອງມີໃນຕູ້ = the MINIMUM pieces of that SKU (confirmed with staff
2026-11-27; it is not the stock on hand). Every SKU opens at 0 on 2026-11-27 and
staff enter the real count as Stock-in. A SKU listed more than once (any case)
takes the largest minimum, not the sum. Subtotal rows (A = ລວມ…) and the grand
total are skipped. A SKU is type + weight + name; column D becomes the SKU's
detail line. Weights become a size in ບາດ (grams / 15); 1 g stays 1 ກລາມ.
"""
import json
import re
import sys
import unicodedata
from collections import OrderedDict
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase" / "reset" / "20261127_morning_market_reset.sql"
FIX_OUT = ROOT / "supabase" / "reset" / "20261127_mm_min_and_zero_opening.sql"
BRANCH = "B-MM"
OPEN_DATE = "2026-11-27"

# Spelling fixes (whole-word replacements inside names / types), in order.
FIXES = [
    ("ປ້ອງອອ້ອຍ", "ປ້ອງອ້ອຍ"),
    ("ດູງງ", "ດູກງູ"),
    ("ຍ່ອຍ", "ຍ້ອຍ"),
    ("ໃຫ່ຍ", "ໃຫຍ່"),
    ("ໃຫ່ມ", "ໃໝ່"),
    ("ໝ້າໂຕະ", "ໜ້າໂຕະ"),
    ("ຍີງ", "ຍິງ"),
]
# Whole names that mean the same product.
SAME_NAME = {
    "ພະປະຈຳເກີດ": "ພະປະຈຳວັນເກີດ",
    "ພະຈຳວັນເກີດ": "ພະປະຈຳວັນເກີດ",
    "ພະລວມປະຈຳວັນ": "ພະປະຈຳວັນເກີດ",
}
# Type names: ຄໍແທ່ງ ("neck bar") is the gold bar ຄຳແທ່ງ.
TYPE_FIX = {"ຄໍແທ່ງ": "ຄຳແທ່ງ"}
# Rounded grams in the sheet -> the Baht they stand for.
BAHT_OF_GRAMS = {0.75: 0.05, 1.12: 0.075, 1.87: 0.125}
ICON = [("ສາຍຄໍ", "necklace"), ("ສາຍແຂນ", "bracelet"), ("ແຫວນ", "ring"), ("ຕຸ້ງຫູ", "ring"), ("ກີ້", "necklace"), ("ຄຳແທ່ງ", "bar"), ("ແຜ່ນຄຳ", "bar")]

changes = []


def norm(s):
    if s is None:
        return ""
    s = unicodedata.normalize("NFC", str(s))
    return re.sub(r"\s+", " ", s.replace(" ", " ")).strip()


def fix(text, where):
    out = text
    for a, b in FIXES:
        out = out.replace(a, b)
    out = SAME_NAME.get(out, out)
    if out != text:
        changes.append((where, text, out))
    return out


def sql(v):
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def size_of(grams, type_name):
    if type_name == "ຄຳແທ່ງ" and grams == 1:
        return ("ກລາມ", 1)
    baht = BAHT_OF_GRAMS.get(grams, round(grams / 15, 4))
    return ("ບາດ", baht)


def qty_label(q):
    return ("%.4f" % q).rstrip("0").rstrip(".")


SOURCE = "ລາຍລະອຽດເຄື່ອງຕູ້_1-7 morning market actual.xlsx"
MIN_COMMENT = (
    "-- Minimum pieces per SKU for the branch (column E, ຂັ້ນຕ່ຳທີ່ຕ້ອງມີໃນຕູ້). At or\n"
    "-- below it the app says \"Order now\". A lead time already set is kept.")


def min_values_sql(mins):
    rows = ",\n".join(f"  ('sku', {sql(sid)}, {sql(BRANCH)}, {q})" for sid, q in mins.items())
    return (
        "insert into replenishment_rule (scope, scope_key, branch_id, min_qty) values\n"
        f"{rows}\n"
        "on conflict (scope, scope_key, coalesce(branch_id, '*'))\n"
        "  do update set min_qty = excluded.min_qty, avg_daily_sell = null;")


SUMMARY_SQL = f"""-- Per case: SKUs, opening and current pieces, and the minimums it should hold.
select d.display_name as case_name, count(*) as skus,
       sum(l.opening_qty) as opening_pcs, sum(l.closing_qty) as now_pcs,
       sum(r.min_qty) as min_pcs
  from daily_stock_ledger l
  join desks d using (desk_id)
  left join replenishment_rule r on r.scope = 'sku' and r.scope_key = l.sku_id and r.branch_id = l.branch_id
 where l.ledger_date = date {sql(OPEN_DATE)} and l.branch_id = {sql(BRANCH)}
 group by d.display_name, d.sort_order order by d.sort_order;"""


def fix_sql(cases, mins):
    """For a database the first reset (column E as opening) already loaded."""
    desk_ids = ", ".join(sql(d) for d, _t, _h in cases)
    return f"""-- ============================================================================
-- FIX the Morning Market load (decided 2026-11-27). Generated by
-- scripts/build_mm_seed.py; do not edit by hand.
--
-- The first reset used column E of the case workbook as the opening stock.
-- Column E (ຂັ້ນຕ່ຳທີ່ຕ້ອງມີໃນຕູ້) is the MINIMUM each SKU must have. This:
--   1. Stops, changing nothing, if a {BRANCH} case is already closed on
--      {OPEN_DATE} or has a later day, or if any SKU has sales/returns typed
--      today that its Stock-in does not cover (opening 0 would go below zero).
--   2. Sets every {OPEN_DATE} opening in {BRANCH} to 0. Stock-in, sales and the
--      rest typed today are kept: staff enter the real count as Stock-in.
--   3. Sets each case's frozen "original stock" to 0 pcs / 0 Baht.
--   4. Saves {len(mins)} minimums (a SKU listed twice takes the larger number).
-- Run once in the Supabase SQL editor. One transaction.
-- ============================================================================
begin;

-- 1. Guards.
do $$
declare bad text;
begin
  if (select count(*) from desks where desk_id in ({desk_ids})) <> {len(cases)} then
    raise exception 'MM_FIX_NOT_LOADED: the Morning Market cases are not in this database; run the full reset instead';
  end if;
  select string_agg(d.display_name || ' ' || to_char(dd.ledger_date, 'YYYY-MM-DD') || ' (' || dd.status || ')', ', ' order by d.sort_order, dd.ledger_date)
    into bad
    from desk_days dd join desks d using (desk_id)
   where dd.branch_id = {sql(BRANCH)}
     and (dd.ledger_date > date {sql(OPEN_DATE)} or (dd.ledger_date = date {sql(OPEN_DATE)} and dd.status = 'done'));
  if bad is not null then
    raise exception 'MM_FIX_BLOCKED: reopen these case days first: %', bad;
  end if;
  select string_agg(d.display_name || ' ' || l.sku_id || ' ' || m.name_lo || ' (' || (l.closing_qty - l.opening_qty) || ')', ', ' order by d.sort_order, l.sku_id)
    into bad
    from daily_stock_ledger l join desks d using (desk_id) join master_sku m using (sku_id)
   where l.ledger_date = date {sql(OPEN_DATE)} and l.branch_id = {sql(BRANCH)}
     and l.closing_qty - l.opening_qty < 0;
  if bad is not null then
    raise exception 'MM_FIX_NEGATIVE: with opening 0 these go below zero; enter their Stock-in first: %', bad;
  end if;
end $$;

-- 2. Openings to 0.
update daily_stock_ledger set opening_qty = 0
 where ledger_date = date {sql(OPEN_DATE)} and branch_id = {sql(BRANCH)} and opening_qty <> 0;

-- 3. Original stock to 0. Its lock is switched off only for this update.
alter table desks disable trigger trg_desk_origin_immutable;
update desks
   set initial_stock = jsonb_build_object(
         'skus', coalesce((select jsonb_object_agg(k, 0) from jsonb_object_keys(initial_stock -> 'skus') k), '{{}}'::jsonb),
         'total_pcs', 0, 'total_baht', 0)
 where desk_id in ({desk_ids}) and initial_stock is not null;
alter table desks enable trigger trg_desk_origin_immutable;

-- 4. {MIN_COMMENT[3:]}
{min_values_sql(mins)}

-- Check, then one audit entry.
do $$ begin
  if (select coalesce(sum(opening_qty), 0) from daily_stock_ledger where ledger_date = date {sql(OPEN_DATE)} and branch_id = {sql(BRANCH)}) <> 0 then
    raise exception 'MM_FIX_CHECK: openings';
  end if;
  if (select count(*) from replenishment_rule r join (values {", ".join(f"({sql(s)}, {q})" for s, q in mins.items())}) v(sku_id, q)
        on r.scope = 'sku' and r.scope_key = v.sku_id and r.branch_id = {sql(BRANCH)} and r.min_qty = v.q) <> {len(mins)} then
    raise exception 'MM_FIX_CHECK: minimums';
  end if;
end $$;
insert into audit_log (actor_name, action, target, detail)
values ('system', 'data.min_reset', {sql(BRANCH)}, jsonb_build_object('source', {sql(SOURCE)}, 'date', {sql(OPEN_DATE)},
        'openings', 0, 'minimums', {len(mins)}));

commit;

{SUMMARY_SQL}"""


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    types = OrderedDict()  # name -> type_id
    sizes = OrderedDict()  # (unit, qty) -> weight_id
    skus = OrderedDict()  # (type, unit, qty, name) -> {sku_id, detail, ...}
    cases = []  # [(desk_id, name, [sku_id, ...])]
    mins = OrderedDict()  # sku_id -> minimum pieces (largest of its rows)
    for n, ws in enumerate(wb.worksheets, start=1):
        merged = {}
        for rng in ws.merged_cells.ranges:
            top = ws.cell(rng.min_row, rng.min_col).value
            for r in range(rng.min_row, rng.max_row + 1):
                for c in range(rng.min_col, rng.max_col + 1):
                    merged[(r, c)] = top
        val = lambda r, c: merged.get((r, c), ws.cell(r, c).value)
        holding = OrderedDict()
        last_type, last_grams = None, None
        for r in range(3, ws.max_row + 1):
            a, b, c, d, e = (val(r, i) for i in range(1, 6))
            a_txt = norm(a)
            if a_txt.startswith("ລວມ"):
                continue
            if not isinstance(e, (int, float)) or e <= 0:
                continue
            type_name = a_txt or last_type
            grams = float(b) if isinstance(b, (int, float)) else last_grams
            last_type, last_grams = type_name, grams
            type_name = TYPE_FIX.get(type_name, type_name)
            if type_name != a_txt and a_txt:
                changes.append((f"{ws.title} row {r} type", a_txt, type_name))
            type_name = fix(type_name, f"{ws.title} row {r} type")
            name = norm(c)
            detail = norm(d)
            # ຕູ້7 writes the ring size into the name too: column D wins.
            m = re.match(r"^(.*?)\s+(ເບີ\S+)$", name)
            if m:
                changes.append((f"{ws.title} row {r} name", name, m.group(1)))
                name = m.group(1)
                detail = detail or m.group(2)
            name = fix(name, f"{ws.title} row {r} name") if name else type_name
            detail = fix(detail, f"{ws.title} row {r} detail") if detail else ""
            unit, q = size_of(round(grams, 2), type_name)
            types.setdefault(type_name, f"T{len(types) + 1:02d}")
            sizes.setdefault((unit, q), None)
            key = (type_name, unit, q, name)
            if key not in skus:
                skus[key] = {"sku_id": f"MM{len(skus) + 1:04d}", "detail": detail}
            elif detail and skus[key]["detail"] and detail != skus[key]["detail"]:
                changes.append((f"{ws.title} row {r} merged into one SKU", f"{name} {detail}", f"{name} {skus[key]['detail']}"))
            sid = skus[key]["sku_id"]
            if sid in mins and mins[sid] != int(e):
                changes.append((f"{ws.title} row {r} repeated SKU, min = largest", f"{name} {mins[sid]}", f"{name} {max(mins[sid], int(e))}"))
            mins[sid] = max(mins.get(sid, 0), int(e))
            holding[sid] = None
        cases.append((f"MM-D{n:02d}", norm(ws.title), list(holding)))

    # Size ids, biggest unit first then by amount.
    ordered = sorted(sizes, key=lambda k: (0 if k[0] == "ບາດ" else 1, k[1]))
    for i, k in enumerate(ordered, start=1):
        sizes[k] = (f"WMM{i:02d}", i)

    L = []
    w = L.append
    w("-- ============================================================================")
    w("-- RESET to the Morning Market cases (decided 2026-11-27). Generated by")
    w("-- scripts/build_mm_seed.py from the case workbook; do not edit by hand.")
    w("--")
    w("-- Run AFTER migration 20261127_21_min_stock.sql, in the Supabase SQL editor.")
    w("-- One transaction: if anything fails, nothing changes.")
    w("--   1. Copies every table it empties into schema kpv_backup_20261127.")
    w("--   2. Empties, in EVERY branch: documents, transfers, stock days and")
    w("--      ledger, cases, case assignments, min/lead rules, SKUs, sizes, types.")
    w("--      Users, branches, units, closed days, settings, gold prices and the")
    w("--      audit log are kept.")
    w(f"--   3. Loads {len(types)} types, {len(sizes)} sizes, {len(skus)} SKUs, {len(mins)} minimums")
    w(f"--      and {len(cases)} cases (ຕູ້1..ຕູ້7, {BRANCH}) checked in on {OPEN_DATE} with every")
    w("--      opening at 0: staff enter the real count as Stock-in.")
    w("-- ============================================================================")
    w("begin;")
    w("")
    w("-- 1. Backup (a second run keeps the first backup).")
    w("create schema if not exists kpv_backup_20261127;")
    wipe = [
        "document_rows", "documents", "transfers", "daily_stock_ledger", "desk_days",
        "staff_main_case", "desk_assignment", "replenishment_rule", "branch_sku", "desks",
        "master_sku", "sku_weight", "sku_type",
    ]
    for t in wipe:
        w(f"do $$ begin if to_regclass('kpv_backup_20261127.{t}') is null then "
          f"execute 'create table kpv_backup_20261127.{t} as table public.{t}'; end if; end $$;")
    w("")
    w("-- 2. Empty. Guard triggers (Done-day lock, role checks, audit) are switched")
    w("--    off only for these deletes and back on before anything is loaded.")
    for t in wipe:
        w(f"alter table {t} disable trigger user;")
    for t in wipe:
        w(f"delete from {t};")
    for t in wipe:
        w(f"alter table {t} enable trigger user;")
    w("")
    w("-- 3. Load.")
    w("insert into sku_type (type_id, name_en, name_lo, icon, active, sort_order) values")
    rows = []
    for i, (name, tid) in enumerate(types.items(), start=1):
        icon = next((ic for prefix, ic in ICON if name.startswith(prefix)), "ring")
        rows.append(f"  ({sql(tid)}, {sql(name)}, {sql(name)}, {sql(icon)}, true, {i})")
    w(",\n".join(rows) + ";")
    w("")
    w("-- Sizes: grams from the unit list, so they follow Settings > Units.")
    w("insert into sku_weight (weight_id, name_en, qty, unit, parts, gram_value, active, sort_order)")
    w("select v.weight_id, v.qty_label || ' ' || v.unit, v.qty, v.unit,")
    w("       jsonb_build_array(jsonb_build_object('unit', v.unit, 'qty', v.qty)),")
    w("       round(v.qty * u.gram_value, 4), true, v.sort_order")
    w("  from (values")
    rows = []
    for (unit, q), (wid, order) in sizes.items():
        rows.append(f"    ({sql(wid)}, {sql(qty_label(q))}, {q}::numeric, {sql(unit)}, {order})")
    w(",\n".join(rows))
    w("  ) as v(weight_id, qty_label, qty, unit, sort_order)")
    w("  join sku_unit u on u.unit = v.unit;")
    w("")
    w("do $$ begin")
    w(f"  if (select count(*) from sku_weight) <> {len(sizes)} then")
    w("    raise exception 'UNIT_MISSING: add the units ບາດ and ກລາມ in Settings > Units first';")
    w("  end if;")
    w("end $$;")
    w("")
    w("insert into master_sku (sku_id, name_en, name_lo, detail, category, type_id, weight_id, std_gram_weight, baht_weight, reorder_level, active, icon)")
    w("select v.sku_id, v.name, v.name, nullif(v.detail, ''), t.name_en, t.type_id, s.weight_id, s.gram_value, round(s.gram_value / 15.244, 4), 0, true, t.icon")
    w("  from (values")
    rows = []
    for (tname, unit, q, name), info in skus.items():
        rows.append(f"    ({sql(info['sku_id'])}, {sql(name)}, {sql(info['detail'])}, {sql(types[tname])}, {sql(sizes[(unit, q)][0])})")
    w(",\n".join(rows))
    w("  ) as v(sku_id, name, detail, type_id, weight_id)")
    w("  join sku_type t on t.type_id = v.type_id")
    w("  join sku_weight s on s.weight_id = v.weight_id;")
    w("")
    w(f"insert into branch_sku (branch_id, sku_id, carried) select {sql(BRANCH)}, sku_id, true from master_sku;")
    w("")
    w(MIN_COMMENT)
    w(min_values_sql(mins))
    w("")
    w("-- Cases, each with its frozen starting stock (every SKU at 0).")
    for i, (desk_id, title, held) in enumerate(cases, start=1):
        skus_json = json.dumps({sid: 0 for sid in held}, ensure_ascii=False)
        w(f"insert into desks (desk_id, branch_id, display_name, active, sort_order, initial_stock)")
        w(f"values ({sql(desk_id)}, {sql(BRANCH)}, {sql(title)}, true, {i},")
        w(f"        jsonb_build_object('skus', {sql(skus_json)}::jsonb, 'total_pcs', 0, 'total_baht', 0));")
    w("")
    w(f"insert into desk_days (desk_id, ledger_date, branch_id, status)")
    w(f"select desk_id, date {sql(OPEN_DATE)}, branch_id, 'check_in' from desks;")
    w("")
    w("insert into daily_stock_ledger (ledger_date, desk_id, branch_id, sku_id, opening_qty) values")
    rows = []
    for desk_id, _title, held in cases:
        for sid in held:
            rows.append(f"  (date {sql(OPEN_DATE)}, {sql(desk_id)}, {sql(BRANCH)}, {sql(sid)}, 0)")
    w(",\n".join(rows) + ";")
    w("")
    w("-- 4. Check, then one audit entry for the whole reset.")
    w("do $$ begin")
    w(f"  if (select count(*) from master_sku) <> {len(skus)} then raise exception 'RESET_CHECK: SKU count'; end if;")
    w(f"  if (select count(*) from desks) <> {len(cases)} then raise exception 'RESET_CHECK: case count'; end if;")
    w(f"  if (select count(*) from daily_stock_ledger) <> {sum(len(h) for _d, _t, h in cases)} then raise exception 'RESET_CHECK: ledger rows'; end if;")
    w(f"  if (select count(*) from replenishment_rule where branch_id = {sql(BRANCH)} and min_qty is not null) <> {len(mins)} then raise exception 'RESET_CHECK: minimums'; end if;")
    w("end $$;")
    w("insert into audit_log (actor_name, action, target, detail)")
    w(f"values ('system', 'data.reset', {sql(BRANCH)}, jsonb_build_object('source', {sql(SOURCE)}, 'date', {sql(OPEN_DATE)},")
    w(f"        'types', {len(types)}, 'sizes', {len(sizes)}, 'skus', {len(skus)}, 'cases', {len(cases)}, 'pcs', 0, 'minimums', {len(mins)}, 'backup_schema', 'kpv_backup_20261127'));")
    w("")
    w("commit;")
    w("")
    w(SUMMARY_SQL)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    FIX_OUT.write_text(fix_sql(cases, mins) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(types)} types, {len(sizes)} sizes, {len(skus)} SKUs, {len(cases)} cases, {len(mins)} minimums, openings 0")
    print(f"wrote {FIX_OUT.relative_to(ROOT)}")
    for desk_id, title, held in cases:
        print(f"  {desk_id} {title}: {len(held)} SKUs, minimums total {sum(mins[s] for s in held)} pcs")
    print("changes:")
    seen = set()
    for where, a, b in changes:
        if (a, b) in seen:
            continue
        seen.add((a, b))
        print(f"  {a} -> {b}   ({where})")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "ລາຍລະອຽດເຄື່ອງຕູ້_1-7 morning market actual.xlsx"))
