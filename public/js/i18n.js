export function getLang() {
  try {
    return localStorage.getItem("kpv_lang") || "lo";
  } catch {
    return "lo";
  }
}

export function setLang(lang) {
  try {
    localStorage.setItem("kpv_lang", lang);
  } catch {}
}

export function t(key) {
  const lang = getLang();
  return (DICT[lang] && DICT[lang][key]) ?? DICT.lo[key] ?? DICT.en[key] ?? key;
}

export function pickName(nameEn, nameLo) {
  return getLang() === "lo" && nameLo ? nameLo : nameEn;
}
