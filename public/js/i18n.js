export function getLang() {
  try {
    return localStorage.getItem("kpv_lang") || "lo";
  } catch {
    return "lo";
  }
}

export function setLang(lang) {
  try {
    localStorage.setItem("kpv_lang", lang);
  } catch {}
}

export function t(key) {
  const lang = getLang();
  return (DICT[lang] && DICT[lang][key]) ?? DICT.lo[key] ?? DICT.en[key] ?? key;
}

// t() with {placeholders}.
export function tf(key, vars) {
  // One pass over the template: values are inserted literally and never re-scanned.
  return t(key).replace(/\{(\w+)\}/g, (m, k) => (Object.hasOwn(vars, k) ? String(vars[k]) : m));
}

export function pickName(nameEn, nameLo) {
  return getLang() === "lo" && nameLo ? nameLo : nameEn;
}

// Product names (SKUs, SKU types) are always shown in Lao, whatever the UI
// language: the shop staff know the products by their Lao names. English only
// when no Lao name is set.
export function productName(nameEn, nameLo) {
  return nameLo || nameEn;
}
